    public function run(): void
    {
        DB::beginTransaction();

        try {

            $this->command->info('🚀 بدء SermonDatabaseSeeder...');

            // =========================================================
            // 1. جلب المساجد الموجودة
            // =========================================================

            $mosques = Mosque::query()
                ->orderBy('id')
                ->get();

            if ($mosques->isEmpty()) {
                throw new \Exception(
                    '❌ لا توجد مساجد في قاعدة البيانات. شغّل MosqueSeeder أولاً.'
                );
            }

            $this->command->info(
                '🕌 عدد المساجد الموجودة: ' . $mosques->count()
            );

            // =========================================================
            // 2. جلب Role مدير المسجد
            // =========================================================

            $mosqueManagerRole = Role::where('name', 'mosque_manager')->first();

            if (!$mosqueManagerRole) {
                throw new \Exception(
                    '❌ Role "mosque_manager" غير موجود. شغّل RoleSeeder أولاً.'
                );
            }

            // =========================================================
            // 3. جلب مدراء المساجد
            // =========================================================

            $managers = User::query()
                ->whereHas('roles', function ($query) use ($mosqueManagerRole) {
                    $query->where('roles.id', $mosqueManagerRole->id);
                })
                ->orderBy('id')
                ->get();

            if ($managers->isEmpty()) {
                throw new \Exception(
                    '❌ لا يوجد مستخدمون بدور mosque_manager.'
                );
            }

            $this->command->info(
                '👤 مدراء المساجد الموجودون: ' . $managers->count()
            );

            // =========================================================
            // 4. جلب Role مدير المنطقة
            // =========================================================

            $regionManagerRole = Role::where('name', 'region_manager')->first();

            $regionManagers = collect();

            if ($regionManagerRole) {
                $regionManagers = User::query()
                    ->whereHas('roles', function ($query) use ($regionManagerRole) {
                        $query->where('roles.id', $regionManagerRole->id);
                    })
                    ->orderBy('id')
                    ->get();
            }

            $this->command->info(
                '👔 مدراء المناطق الموجودون: ' . $regionManagers->count()
            );

            // =========================================================
            // 5. ربط كل مسجد بمدير مسجد
            // =========================================================

            $managerMosqueMap = [];

            foreach ($mosques as $index => $mosque) {

                /*
                 * الأولوية:
                 *
                 * 1. مدير لديه mosque_id يساوي المسجد.
                 * 2. مدير لديه mosque_id = null يتم اختياره.
                 * 3. توزيع المدراء الموجودين بالتناوب.
                 */

                $manager = $managers->firstWhere(
                    'mosque_id',
                    $mosque->id
                );

                if (!$manager) {
                    $manager = $managers
                        ->filter(fn ($user) => empty($user->mosque_id))
                        ->first();
                }

                if (!$manager) {
                    $manager = $managers[
                    $index % $managers->count()
                    ];
                }

                $managerMosqueMap[$mosque->id] = $manager;

                $this->command->info(
                    "🕌 {$mosque->name} ← 👤 {$manager->name}"
                );
            }

            // =========================================================
            // 6. إنشاء الخطب
            // =========================================================

            $sermonCount = 0;
            $selectionCount = 0;
            $attachmentCount = 0;

            foreach ($mosques as $mosqueIndex => $mosque) {

                $manager = $managerMosqueMap[$mosque->id];

                /*
                 * مدير المنطقة:
                 *
                 * إذا كان لدينا مدراء مناطق نوزعهم على المساجد.
                 */
                $regionManager = null;

                if ($regionManagers->isNotEmpty()) {
                    $regionManager = $regionManagers[
                    $mosqueIndex % $regionManagers->count()
                    ];
                }

                $this->command->info('');
                $this->command->info(
                    "📖 إنشاء خطب للمسجد: {$mosque->name}"
                );

                // -----------------------------------------------------
                // إنشاء 8 خطب لكل مسجد
                // -----------------------------------------------------

                for ($i = 0; $i < 8; $i++) {

                    $sermonData = $this->sermonContents[
                    ($mosqueIndex * 8 + $i)
                    % count($this->sermonContents)
                    ];

                    /*
                     * الحالات موزعة لتجربة لوحة التحكم.
                     */
                    $status = match ($i % 4) {
                        0 => 'Archived',
                        1 => 'Archived',
                        2 => 'Pending',
                        default => 'Rejected',
                    };

                    /*
                     * تواريخ مختلفة خلال الأشهر الماضية.
                     */
                    $sermonDate = Carbon::today()
                        ->subWeeks(($mosqueIndex * 2) + $i + 1)
                        ->startOfWeek(Carbon::FRIDAY);

                    $sermon = Sermon::create([
                        'title' => $sermonData['title'],

                        'content' => $sermonData['content'],

                        'speaker_name' => $this->speakerNames[
                        ($mosqueIndex + $i)
                        % count($this->speakerNames)
                        ],

                        'sermon_date' => $sermonDate->toDateString(),

                        'status' => $status,

                        'notes' => match ($status) {
                            'Pending' =>
                            'بانتظار مراجعة مدير المنطقة.',

                            'Rejected' =>
                            'يرجى مراجعة محتوى الخطبة وإعادة تقديمها.',

                            default =>
                            'تمت مراجعة الخطبة وأرشفتها.',
                        },

                        'mosque_manager_id' => $manager->id,

                        'region_manager_id' => $regionManager?->id,
                    ]);

                    $sermonCount++;

                    // -------------------------------------------------
                    // إنشاء مرفقات لبعض الخطب
                    // -------------------------------------------------

                    if ($i % 2 === 0) {

                        SermonAttachement::create([
                            'sermon_id' => $sermon->id,

                            'file_path' =>
                                'sermons/' .
                                $mosque->id .
                                '/sermon_' .
                                $sermon->id .
                                '.pdf',

                            'file_type' => 'pdf',
                        ]);

                        $attachmentCount++;
                    }

                    if ($i % 3 === 0) {

                        SermonAttachement::create([
                            'sermon_id' => $sermon->id,

                            'file_path' =>
                                'sermons/' .
                                $mosque->id .
                                '/sermon_' .
                                $sermon->id .
                                '.docx',

                            'file_type' =>
                                'docx',
                        ]);

                        $attachmentCount++;
                    }

                    // -------------------------------------------------
                    // إنشاء اختيار خطبة ليوم جمعة
                    // -------------------------------------------------

                    /*
                     * فقط الخطب المؤرشفة يتم اختيارها.
                     */
                    if (
                        $status === 'Archived'
                        && $sermonDate->isPast()
                    ) {

                        /*
                         * نتأكد من عدم وجود اختيار مسبق
                         * لنفس المدير والتاريخ.
                         */
                        $exists = SermonSelection::where(
                            'mosque_manager_id',
                            $manager->id
                        )
                            ->where(
                                'friday_date',
                                $sermonDate->toDateString()
                            )
                            ->exists();

                        if (!$exists) {

                            SermonSelection::create([
                                'mosque_manager_id' =>
                                    $manager->id,

                                'sermon_id' =>
                                    $sermon->id,

                                'friday_date' =>
                                    $sermonDate->toDateString(),
                            ]);

                            $selectionCount++;
                        }
                    }

                    $this->command->info(
                        "  ✓ {$sermonData['title']} | {$status}"
                    );
                }
            }

            // =========================================================
            // 7. Commit
            // =========================================================

            DB::commit();

            // =========================================================
            // 8. Summary
            // =========================================================

            $this->command->info('');
            $this->command->info(
                '━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━'
            );

            $this->command->info(
                '✅ تم تنفيذ SermonDatabaseSeeder بنجاح'
            );

            $this->command->info(
                '━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━'
            );

            $this->command->info(
                '🕌 المساجد: ' . $mosques->count()
            );

            $this->command->info(
                '👤 مدراء المساجد: ' . $managers->count()
            );

            $this->command->info(
                '👔 مدراء المناطق: ' . $regionManagers->count()
            );

            $this->command->info(
                '📖 الخطب: ' . $sermonCount
            );

            $this->command->info(
                '📎 المرفقات: ' . $attachmentCount
            );

            $this->command->info(
                '📅 اختيارات الخطب: ' . $selectionCount
            );

            $this->command->info(
                '━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━'
            );

        } catch (\Throwable $e) {

            DB::rollBack();

            $this->command->error('');
            $this->command->error(
                '❌ فشل SermonDatabaseSeeder'
            );

            $this->command->error(
                '📍 الملف: ' . __FILE__
            );

            $this->command->error(
                '📍 السطر: ' . $e->getLine()
            );

            $this->command->error(
                '💥 الخطأ: ' . $e->getMessage()
            );

            throw $e;
        }
    }
}
